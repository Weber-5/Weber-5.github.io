import type { Localized } from '../lib/data';

export const LANGS = ['en', 'zh'] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = 'en';

/** getStaticPaths entries for the `[...locale]` rest parameter. */
export const localeParams = () => [
  { params: { locale: undefined }, props: { lang: 'en' as Lang } },
  { params: { locale: 'zh' }, props: { lang: 'zh' as Lang } },
];

/** Read a bilingual content field, falling back to whichever language exists. */
export function tr(value: Localized | undefined, lang: Lang): string {
  if (value === undefined) return '';
  if (typeof value === 'string') return value;
  return value[lang] ?? value.en ?? value.zh ?? '';
}

/** Prefix an internal path with the locale. `path` is written as in English. */
export function href(path: string, lang: Lang): string {
  return lang === 'zh' ? `/zh${path}` : path;
}

/** Strip the locale prefix from a pathname. */
export function basePath(pathname: string): string {
  const stripped = pathname.replace(/^\/zh(?=\/|$)/, '');
  return stripped === '' ? '/' : stripped;
}

